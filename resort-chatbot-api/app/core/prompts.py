#: ประโยคปฏิเสธประจำภาษา — ต้องเป็นข้อความตายตัวคำต่อคำ
#: เพราะ rag_pipeline ใช้ประโยคนี้ตรวจว่าโมเดล "ตอบได้" หรือ "ปฏิเสธ"
#: (ดู ChatResponse.answered) ถ้าแก้ข้อความตรงนี้ต้องแก้ให้ตรงกันทั้งสองที่
NO_CONTEXT_ANSWER_BY_LANGUAGE: dict[str, str] = {
    "th": "ขออภัยค่ะ ไม่มีข้อมูลเรื่องนี้ในระบบ รบกวนสอบถามโดยตรงที่ 081-598-1199 นะคะ",
    "en": (
        "Sorry, we do not have that information in our system. "
        "Please contact us directly at 081-598-1199."
    ),
}

#: ค่าเริ่มต้นสำหรับโค้ดที่ไม่ได้ระบุภาษา
NO_CONTEXT_ANSWER = NO_CONTEXT_ANSWER_BY_LANGUAGE["th"]


def no_context_answer(language: str) -> str:
    """คืนประโยคปฏิเสธให้ตรงกับภาษาที่ลูกค้าถาม"""
    return NO_CONTEXT_ANSWER_BY_LANGUAGE.get(language, NO_CONTEXT_ANSWER)


